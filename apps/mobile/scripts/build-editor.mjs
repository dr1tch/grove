import { build } from "vite-plus";
import { readFile, readdir, writeFile } from "node:fs/promises";
import { createHash } from "node:crypto";
import { fileURLToPath } from "node:url";
const root = new URL("../", import.meta.url);
await build({
  configFile: fileURLToPath(new URL("vite.editor.config.ts", root)),
});
const output = new URL(".editor-build/", root);
const files = await readdir(output);
const unexpected = files.filter((name) => !/\.(js|css)$/.test(name));
if (unexpected.length)
  throw new Error(`Editor emitted non-inline assets: ${unexpected.join(", ")}`);
const js = (await readFile(new URL("editor.js", output), "utf8")).replace(
  /<\/script/gi,
  "<\\/script",
);
const css = (
  await Promise.all(
    files
      .filter((name) => name.endsWith(".css"))
      .map((name) => readFile(new URL(name, output), "utf8")),
  )
)
  .join("\n")
  .replace(/<\/style/gi, "<\\/style");
if (/url\(\s*["']?(?:https?:|\/|\.\/|\.\.\/)/i.test(css))
  throw new Error("Editor CSS must not reference external assets");
const scriptHash = createHash("sha256").update(js).digest("base64");
const html = `<!doctype html><html><head><meta charset="UTF-8"><meta name="viewport" content="width=device-width, initial-scale=1, maximum-scale=5"><meta http-equiv="Content-Security-Policy" content="default-src 'none'; script-src 'sha256-${scriptHash}'; style-src 'unsafe-inline'; font-src data:; img-src data:; connect-src 'none'; frame-src 'none'; object-src 'none'; base-uri 'none'; form-action 'none'"><style>${css}</style></head><body><main id="reader" aria-label="Note"></main><div id="editor" hidden></div><script>${js}</script></body></html>`;
await writeFile(
  new URL("editor/generated.ts", root),
  `// Generated by scripts/build-editor.mjs. Do not edit.\nexport const editorHtml = ${JSON.stringify(html)};\n`,
);
console.log(
  `Bundled offline document surface: ${(Buffer.byteLength(html) / 1024 / 1024).toFixed(2)} MiB`,
);
